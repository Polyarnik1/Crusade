export function fill(tpl: string, v: Record<string, string | number | undefined>): string {
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? ''));
}

export function walkKey(km: number): ChronKey {
  return km < 0.8 ? 'walkShort' : km < 3 ? 'walkMid' : km < 8 ? 'walkLong' : 'walkGreat';
}

const SEASONS = ['зима', 'зима', 'весна', 'весна', 'весна', 'лето', 'лето', 'лето', 'осень', 'осень', 'осень', 'зима'];
export const seasonOf = (ts: number) => SEASONS[new Date(ts).getMonth()];

const ROMAN = ['', 'I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X'];

/** «День 7 от основания» / «Год II, день 12»; null, если запись до основания. */
export function reignLabel(ts: number, foundedAt?: number): string | null {
  if (!foundedAt) return null;
  const day = (t: number) => {
    const d = new Date(t);
    return Math.floor(new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() / 86400000 + 0.5);
  };
  const n = day(ts) - day(foundedAt) + 1;
  if (n < 1) return null;
  if (n <= 365) return `День ${n} от основания`;
  const y = Math.floor((n - 1) / 365) + 1;
  return `Год ${ROMAN[y] ?? y}, день ${((n - 1) % 365) + 1}`;
}
